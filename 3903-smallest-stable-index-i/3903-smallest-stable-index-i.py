class Solution(object):
    def firstStableIndex(self, nums, k):
        """
        :type nums: List[int]
        :type k: int
        :rtype: int
        """
        
        for i in range(len(nums)):
            prev = nums[:i+1]
            next = nums[i:]
            if (max(prev)-min(next)) <= k :
                return i
        
        return -1

